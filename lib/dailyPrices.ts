/** Price for a calendar day. null means the cjenik has no price for that date. */
export function getDailyPrice(
  year: number,
  month: number,
  day: number
): number | null {
  const key = `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
  if (!(key in dailyPrices)) return null;
  return dailyPrices[key];
}

export type PricePeriod = {
  from: string;
  to: string;
  price: number;
};

function shiftIso(iso: string, days: number): string {
  const date = new Date(`${iso}T00:00:00Z`);
  date.setUTCDate(date.getUTCDate() + days);
  return date.toISOString().slice(0, 10);
}

function formatDmY(iso: string): string {
  const [year, month, day] = iso.split("-");
  return `${day}.${month}.${year}`;
}

/** Consecutive days that share the same nightly rate, skipping days with no price. */
export function getPricePeriods(): PricePeriod[] {
  const dates = Object.keys(dailyPrices).sort();
  const periods: PricePeriod[] = [];
  let current: { start: string; end: string; price: number } | null = null;

  for (const date of dates) {
    const price = dailyPrices[date];
    if (price == null) {
      if (current) {
        periods.push({
          from: formatDmY(current.start),
          to: formatDmY(current.end),
          price: current.price,
        });
        current = null;
      }
      continue;
    }
    if (
      current &&
      current.price === price &&
      shiftIso(current.end, 1) === date
    ) {
      current.end = date;
      continue;
    }
    if (current) {
      periods.push({
        from: formatDmY(current.start),
        to: formatDmY(current.end),
        price: current.price,
      });
    }
    current = { start: date, end: date, price };
  }

  if (current) {
    periods.push({
      from: formatDmY(current.start),
      to: formatDmY(current.end),
      price: current.price,
    });
  }

  return periods;
}
